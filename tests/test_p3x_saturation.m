function test_p3x_saturation(rootDir, run_id)
%TEST_P3X_SATURATION Acceptance A4 + 01_PROTOCOL_AMENDMENT_X1 (X1-1 + X1-3).
% X1-3: the absolute budget is UNIFIED across capacities for each lambda:
%     B_tight(lambda) = 0.5 * C_full(lambda, C=1)   (min-capacity anchor)
%     B_high(lambda)  = 1.2 * C_full(lambda, C=4)   (max-capacity anchor)
% so the final grid sweeps capacity at FIXED budget (the old per-(lambda,C)
% levels confounded capacity with budget and are superseded -- old values are
% snapshotted under 06_results/<run_id>/snapshot_x3r_pre_repair_*).
% Procedure (dev seed 20261018, results-before-final calibration gate):
%   1. loose probe B_probe = 10*N per (lambda,C): measure C_full(l,C) + utilization;
%   2. freeze the UNIFIED pair per lambda (rule pre-fixed, NOT final tuning);
%   3. gate: B_high must be LOOSE as measured for BOTH capacities (reject <= 2%
%      AND budget_remaining >= 1%*B_high), otherwise raise and RE-FREEZE
%      (recorded gate_factor); gate failure or reversed cost order is REPORTED
%      by failing loudly -- never hidden by changing the metrics;
%   4. archetype coverage judged from measured budget_remaining / utilization /
%      queue evidence, in the numeric matrix, not from nominal labels.
if nargin < 2, run_id = '20261018_171608_963_p3_supplement'; end
outRoot = fullfile(rootDir, '06_results', run_id);
devDir = fullfile(outRoot, 'dev_acceptance', 'test_p3x_saturation');
calDir = fullfile(outRoot, 'dev_acceptance', 'budget_calibration');
if exist(calDir, 'dir') ~= 7, mkdir(calDir); end
devSeed = 20261018;

lams = [0.1, 1.0];
caps = [1, 4];
probe = cell(2, 2);      % probe{li, ci}
tight = cell(2, 2);
high = cell(2, 2);
calCells = cell(2, 1);

for li = 1:2
    lam = lams(li);
    Cfull = zeros(1, 2);
    utilP = zeros(1, 2);
    Np = zeros(1, 2);
    for ci = 1:2
        Cc = caps(ci);
        % realized arrival count for this (lambda, seed) determines B_probe = 10*N
        P = p3_default_params();
        P.T_arr = 900; P.W_batch = 300; P.d_int = 10; P.carbon_sigma = 0;
        P.demand_M = 1; P.rho_route = 0; P.lambda = lam; P.C = Cc;
        trajN = p3_gen_trajectory(P, devSeed);
        Np(ci) = trajN.N;
        cfg = dev_cfg(lam, Cc, 10 * Np(ci), sprintf('DEV_E2A_probe_l%g_C%d', lam, Cc));
        [~, exP, recP] = p3x_run_one(cfg, rootDir, fullfile(devDir, cfg.case_id));
        assert(strcmp(recP.status, 'success'), 'p3x:DevRun', 'probe failed for %s', cfg.case_id);
        assert(exP.n_rejected_budget == 0, 'p3x:Probe', ...
            'B_probe=10*N must serve every arrival for (l=%g,C=%d), rejected=%d', ...
            lam, Cc, exP.n_rejected_budget);
        Cfull(ci) = exP.budget_used;
        utilP(ci) = exP.utilization_over_0_to_T_arr;
        probe{li, ci} = exP;
    end
    % reversed cost order would break the pre-fixed anchor rule -> REPORT, do not
    % silently swap the anchors
    assert(Cfull(2) >= Cfull(1) - 1e-9, 'p3x:CostOrder', ...
        ['reversed cost order at lambda=%g: C_full(C=4)=%.4f < C_full(C=1)=%.4f; ', ...
        'report to captain for protocol re-review (rule NOT changed here)'], ...
        lam, Cfull(2), Cfull(1));

    B_tight = 0.5 * Cfull(1);          % X1-3 anchor: min capacity reference
    B_high0 = 1.2 * Cfull(2);          % X1-3 anchor: max capacity reference

    % ---- gate: B_high loose for BOTH capacities, else raise + re-freeze ----
    gateFactor = 1.0;
    for g = 1:4
        gate = true;
        rejRates = zeros(1, 2);
        remFrac = zeros(1, 2);
        for ci = 1:2
            Cc = caps(ci);
            cfgH = dev_cfg(lam, Cc, B_high0 * gateFactor, ...
                sprintf('DEV_E2A_high_l%g_C%d_g%d', lam, Cc, g));
            [~, exH, recH] = p3x_run_one(cfgH, rootDir, fullfile(devDir, cfgH.case_id));
            assert(strcmp(recH.status, 'success'), 'p3x:DevRun', 'high run failed for %s', cfgH.case_id);
            high{li, ci} = exH;
            rejRates(ci) = exH.n_rejected_budget / exH.N_arr;
            remFrac(ci) = exH.budget_remaining_frac;
            gate = gate && (rejRates(ci) <= 0.02) && ...
                (exH.budget_remaining >= 0.01 * exH.B);
        end
        if gate
            break;
        end
        gateFactor = gateFactor * 1.5;   % 结果前上调并重新冻结（记录）
    end
    assert(gate, 'p3x:BudgetGate', ...
        ['B_high still tight after 4 raises for lambda=%g (rej=[%.3f %.3f], rem=[%.3f %.3f]); ', ...
        'report to captain for protocol re-review (metrics NOT altered)'], ...
        lam, rejRates(1), rejRates(2), remFrac(1), remFrac(2));

    % ---- B_tight runs for BOTH capacities (must be measurably tight) -------
    for ci = 1:2
        Cc = caps(ci);
        cfgT = dev_cfg(lam, Cc, B_tight, sprintf('DEV_E2A_tight_l%g_C%d', lam, Cc));
        [~, exT, recT] = p3x_run_one(cfgT, rootDir, fullfile(devDir, cfgT.case_id));
        assert(strcmp(recT.status, 'success'), 'p3x:DevRun', 'tight run failed for %s', cfgT.case_id);
        tight{li, ci} = exT;
        tightIsTight = (exT.n_rejected_budget > 0) || (exT.budget_remaining_frac < 0.10);
        assert(tightIsTight, 'p3x:BudgetTight', ...
            'unified B_tight must be measurably tight at (l=%g,C=%d)', lam, Cc);
    end

    calCells{li} = struct('key', sprintf('lambda=%.17g', lam), 'lambda', lam, ...
        'dev_seed', devSeed, 'N_probe_C1', Np(1), 'N_probe_C4', Np(2), ...
        'B_probe_C1', 10 * Np(1), 'B_probe_C4', 10 * Np(2), ...
        'C_full_C1', Cfull(1), 'C_full_C4', Cfull(2), ...
        'util_probe_C1', utilP(1), 'util_probe_C4', utilP(2), ...
        'cost_order_ok', true, ...
        'B_tight', B_tight, 'B_high', B_high0, 'gate_factor', gateFactor, ...
        'B_high_final', B_high0 * gateFactor, ...
        'high_reject_rate_C1', rejRates(1), 'high_reject_rate_C4', rejRates(2), ...
        'high_remaining_frac_C1', remFrac(1), 'high_remaining_frac_C4', remFrac(2), ...
        'gate_pass', gate);
    fprintf('  lambda=%g: C_full C1=%.3f C4=%.3f | unified B_tight=%.3f B_high=%.3f (gate x%.2f) | rejHigh=[%.3f %.3f] remHigh=[%.3f %.3f]\n', ...
        lam, Cfull(1), Cfull(2), B_tight, B_high0, gateFactor, ...
        rejRates(1), rejRates(2), remFrac(1), remFrac(2));
end

% ---- freeze the calibrated UNIFIED budget axis (hash-bound by p3x_freeze) ----
cal = struct('run_id', run_id, 'dev_seed', devSeed, 'rule_version', 'X1-3', ...
    'rule', ['B_tight(lambda)=0.5*C_full(lambda,C=1); B_high(lambda)=1.2*C_full(lambda,C=4); ', ...
        'same numeric budget for C=1 and C=4 (fixed-budget capacity sweep); ', ...
        'probe B_probe=10*N; gate: reject<=2% and remaining>=1%*B_high for BOTH C else raise factor and re-freeze'], ...
    'archetypes', ['C1+B_high=budget-loose + server-saturated; C4+B_tight=capacity-loose + budget-tight; ', ...
        'C1+B_tight=both tight; C4+B_high=both loose (all measured, not nominal)'], ...
    'cells', {calCells});
p3_write_json(fullfile(calDir, 'budget_calibration.json'), cal);
write_cal_csv(fullfile(calDir, 'budget_calibration.csv'), calCells);

% ---- prototype intervals in the NUMERIC matrix (X1-3 item 5) ---------------
lam1 = 2; lam01 = 1;
assert(high{lam1, 1}.budget_remaining > 0 && high{lam1, 1}.utilization_over_0_to_T_arr > 0.70, ...
    'p3x:Archetype', 'C1+B_high (lambda=1) must be budget-loose (remaining>0) + server-saturated');
assert(tight{lam01, 2}.utilization_over_0_to_T_arr < 0.25 && ...
    tight{lam01, 2}.budget_remaining_frac < 0.10, ...
    'p3x:Archetype', 'C4+B_tight (lambda=0.1) must be capacity-loose (util<0.25) + budget-tight');
assert(tight{lam1, 1}.budget_remaining_frac < 0.10 && ...
    (probe{lam1, 1}.utilization_over_0_to_T_arr > 0.70 || tight{lam1, 1}.stage1_wait_mean > 0), ...
    'p3x:Archetype', 'C1+B_tight (lambda=1) must be both tight (budget + capacity evidence)');
assert(high{lam01, 2}.budget_remaining > 0 && ...
    high{lam01, 2}.utilization_over_0_to_T_arr < 0.25, ...
    'p3x:Archetype', 'C4+B_high (lambda=0.1) must be both loose (remaining>0, util<0.25)');

% ---- per-run report -------------------------------------------------------
hdr = {'case_id','lambda','C','level','B_abs','N_arr','budget_used','budget_remaining', ...
    'budget_remaining_frac','n_rejected_budget','utilization_0_Tarr','stage1_wait_mean_s','dev_seed'};
rows = {};
for li = 1:2
    lam = lams(li);
    Bt = calCells{li}.B_tight;
    Bh = calCells{li}.B_high_final;
    for ci = 1:2
        Cc = caps(ci);
        exH = high{li, ci};
        rows(end+1, :) = {sprintf('DEV_E2A_high_l%g_C%d', lam, Cc), sprintf('%.17g', lam), ...
            sprintf('%d', Cc), 'high', sprintf('%.17g', Bh), sprintf('%d', exH.N_arr), ...
            sprintf('%.17g', exH.budget_used), sprintf('%.17g', exH.budget_remaining), ...
            sprintf('%.17g', exH.budget_remaining_frac), sprintf('%d', exH.n_rejected_budget), ...
            sprintf('%.17g', exH.utilization_over_0_to_T_arr), ...
            sprintf('%.17g', exH.stage1_wait_mean), '20261018'}; %#ok<AGROW>
        exT = tight{li, ci};
        rows(end+1, :) = {sprintf('DEV_E2A_tight_l%g_C%d', lam, Cc), sprintf('%.17g', lam), ...
            sprintf('%d', Cc), 'tight', sprintf('%.17g', Bt), sprintf('%d', exT.N_arr), ...
            sprintf('%.17g', exT.budget_used), sprintf('%.17g', exT.budget_remaining), ...
            sprintf('%.17g', exT.budget_remaining_frac), sprintf('%d', exT.n_rejected_budget), ...
            sprintf('%.17g', exT.utilization_over_0_to_T_arr), ...
            sprintf('%.17g', exT.stage1_wait_mean), '20261018'}; %#ok<AGROW>
    end
end
cols = cell(1, numel(hdr));
for j = 1:numel(hdr)
    cols{j} = rows(:, j);
end
p3_write_csv(fullfile(devDir, 'saturation_report.csv'), hdr, cols);
fprintf('P3X_SATURATION_PASS\n');
end

function cfg = dev_cfg(lam, Cc, Babs, cid)
cfg = struct('block', 'E2A', 'case_id', cid, 'seed', 20261018, ...
    'offset', 96, 'first_index', 1441, 'strategy', 'adaptive_gain', ...
    'carbon_sched', false, 'predictor', 'n/a(unused)', 'lambda', lam, ...
    'C', Cc, 'budget_mode', 'fixed_abs', 'B_abs', Babs, 'T_arr', 900, ...
    'W_batch', 300, 'd_int', 10, 'lag_s', 3600, 'rho_route', 0, 'bias', 0, ...
    'carbon_sigma', 0, 'demand_M', 1, 'note', ...
    'E2A unified-budget calibration dev acceptance (dev seed; X1-3 measured gate)');
end

function write_cal_csv(file, cells)
hdr = {'key','lambda','dev_seed','N_probe_C1','N_probe_C4','B_probe_C1','B_probe_C4', ...
    'C_full_C1','C_full_C4','util_probe_C1','util_probe_C4','cost_order_ok', ...
    'B_tight','B_high','gate_factor','B_high_final', ...
    'high_reject_rate_C1','high_reject_rate_C4','high_remaining_frac_C1', ...
    'high_remaining_frac_C4','gate_pass'};
n = numel(cells);
rows = cell(n, numel(hdr));
for k = 1:n
    e = cells{k};
    rows(k, :) = {e.key, sprintf('%.17g', e.lambda), sprintf('%d', e.dev_seed), ...
        sprintf('%d', e.N_probe_C1), sprintf('%d', e.N_probe_C4), ...
        sprintf('%.17g', e.B_probe_C1), sprintf('%.17g', e.B_probe_C4), ...
        sprintf('%.17g', e.C_full_C1), sprintf('%.17g', e.C_full_C4), ...
        sprintf('%.17g', e.util_probe_C1), sprintf('%.17g', e.util_probe_C4), ...
        char(string(e.cost_order_ok)), sprintf('%.17g', e.B_tight), ...
        sprintf('%.17g', e.B_high), sprintf('%.17g', e.gate_factor), ...
        sprintf('%.17g', e.B_high_final), sprintf('%.17g', e.high_reject_rate_C1), ...
        sprintf('%.17g', e.high_reject_rate_C4), sprintf('%.17g', e.high_remaining_frac_C1), ...
        sprintf('%.17g', e.high_remaining_frac_C4), char(string(e.gate_pass))};
end
cols = cell(1, numel(hdr));
for j = 1:numel(hdr)
    cols{j} = rows(:, j);
end
p3_write_csv(file, hdr, cols);
end
